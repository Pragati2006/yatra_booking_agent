"""
tests/test_browser_my_account_e2e.py
End-to-End browser test verifying the exact user workflow:
1. User logs in via passwordless email OTP.
2. User navigates through Step 1 -> Step 2 -> Step 3.
3. User completes Playwright RPA workflow (OTP + CAPTCHA).
4. Step 4 Confirmation displays the confirmed booking reference.
5. User opens My Account & Saved History -> My Bookings.
6. The page displays "My Bookings (1)" and the booking card with full details.
7. Booking reference is identical to Step 4 and PDF pass.
8. Refreshing preserves the booking card.
"""

import os
import sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import time
import uuid
from playwright.sync_api import sync_playwright
from agents.auth_service import get_email_provider

def run_browser_test():
    provider = get_email_provider()
    test_email = f"devotee_{uuid.uuid4().hex[:6]}@example.com"
    print(f"Testing with email: {test_email}")

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(viewport={"width": 1280, "height": 800})
        page = context.new_page()

        # 1. Open app
        print("Navigating to http://localhost:5173...")
        page.goto("http://localhost:5173", timeout=15000)
        page.wait_for_selector("nav", timeout=10000)

        # 2. Open Auth Modal & Login
        print("Opening login modal...")
        page.click("button:has-text('Sign In')")
        page.wait_for_selector("[data-testid='auth-modal']", timeout=5000)

        page.fill("input[type='email']", test_email)
        page.click("button:has-text('Send Verification Code')")

        # Wait for OTP to be generated by backend mock provider
        time.sleep(1)
        import requests
        otp_res = requests.get(f"http://localhost:8000/api/auth/test/latest-otp", params={"email": test_email}, timeout=5)
        otp = otp_res.json().get("latest_otp") if otp_res.status_code == 200 else provider.get_latest_otp_for(test_email)
        assert otp, f"Failed to get mock OTP for {test_email}"
        print(f"Got OTP: {otp}")

        page.fill("[data-testid='auth-otp-input']", otp)
        page.click("button:has-text('Verify Code & Sign In')")
        page.wait_for_selector("button:has-text('Continue to Application')", timeout=5000)
        page.click("button:has-text('Continue to Application')")

        # Verify user is signed in
        page.wait_for_selector(f"button:has-text('{test_email}')", timeout=5000)
        print(f"Successfully signed in as {test_email}!")

        # 3. Navigate to Booking Tab
        print("Navigating to Darshan Bookings...")
        page.click("button:has-text('Darshan Bookings')")
        page.wait_for_selector("[data-testid='plan-my-yatra-btn']", timeout=10000)

        # Step 1: Click Plan My Yatra
        page.click("[data-testid='plan-my-yatra-btn']")
        print("Plan My Yatra clicked, waiting for Step 2...")

        # Step 2: Recommended Yatra
        page.wait_for_selector("[data-testid='proceed-to-review-btn']", timeout=20000)
        print("Step 2 reached, clicking Proceed to Booking Review & RPA...")
        page.click("[data-testid='proceed-to-review-btn']")

        # Step 3: Booking Review & RPA
        page.wait_for_selector("[data-testid='bottom-start-yatra-rpa-btn']", timeout=10000)
        print("Step 3 reached, initiating unified RPA booking...")
        page.click("[data-testid='bottom-start-yatra-rpa-btn']")

        # RPA Intervention Modal should pop up with OTP challenge
        page.wait_for_selector("[data-testid='rpa-intervention-modal']", timeout=15000)
        print("RPA Intervention Modal displayed! Clearing OTP checkpoint...")
        page.click("[data-testid='rpa-simulate-btn']")

        # Next is CAPTCHA checkpoint
        print("Waiting for CAPTCHA checkpoint...")
        time.sleep(1.5)
        page.wait_for_selector("[data-testid='rpa-simulate-btn']", timeout=15000)
        page.click("[data-testid='rpa-simulate-btn']")

        # Resuming to confirmation
        print("Simulated payment submitted, waiting for completion...")
        page.wait_for_selector("[data-testid='continue-to-confirmation-btn']", timeout=20000)
        print("RPA completed! Continuing to Step 4 Confirmation...")
        page.click("[data-testid='continue-to-confirmation-btn']")

        # Step 4: Confirmation Page
        page.wait_for_selector("[data-testid='step-4-confirmation-page']", timeout=10000)
        booking_ref_el = page.wait_for_selector("[data-testid='booking-reference-badge']", timeout=5000)
        booking_ref = booking_ref_el.text_content().strip()
        print(f"Step 4 Confirmation Booking Ref: {booking_ref}")
        assert booking_ref.startswith("VD-"), f"Unexpected booking reference: {booking_ref}"

        # 4. Open My Account & Saved History
        print("Opening My Account modal...")
        page.click(f"button:has-text('{test_email}')")
        page.wait_for_selector("[data-testid='tab-bookings']", timeout=5000)

        # 5. Check My Bookings Tab Counter
        tab_text = page.text_content("[data-testid='tab-bookings']").strip()
        print(f"My Bookings tab text: {tab_text}")
        assert "My Bookings (1)" in tab_text, f"Expected 'My Bookings (1)', got '{tab_text}'"

        # 6. Check Booking Card
        card = page.wait_for_selector(f"[data-testid='booking-card-{booking_ref}']", timeout=5000)
        assert card, f"Booking card for {booking_ref} not found!"
        card_text = card.text_content()
        print("Found booking card content:")
        print(card_text[:200] + "...")

        assert booking_ref in card_text, "Booking reference must appear on card"
        assert "LOCAL MOCK PORTAL / DEMO" in card_text, "Demo label must appear on card"
        assert "NOT AN OFFICIAL SHRINE BOARD BOOKING" in card_text, "Official disclaimer must appear on card"
        assert "SIMULATED_CONFIRMED" in card_text or "Sandbox Paid" in card_text, "Status must appear on card"

        # 7. Check View Details
        print("Checking View Details button...")
        page.click(f"[data-testid='view-details-btn-{booking_ref}']")
        page.wait_for_selector("[data-testid='modal-download-pass-btn']", timeout=5000)
        print("View Details modal opened successfully!")
        page.click("button:has-text('Close')")

        # 8. Check Page Refresh Persistence
        print("Refreshing browser to test persistence...")
        page.reload()
        page.wait_for_selector(f"button:has-text('{test_email}')", timeout=10000)

        # Open My Account again
        page.click(f"button:has-text('{test_email}')")
        page.wait_for_selector("[data-testid='tab-bookings']", timeout=5000)

        tab_text_after = page.text_content("[data-testid='tab-bookings']").strip()
        print(f"After refresh My Bookings tab text: {tab_text_after}")
        assert "My Bookings (1)" in tab_text_after, f"Expected 'My Bookings (1)' after refresh, got '{tab_text_after}'"

        card_after = page.wait_for_selector(f"[data-testid='booking-card-{booking_ref}']", timeout=5000)
        assert card_after, "Booking card must persist after page refresh!"

        print("\n=======================================================")
        print("🎉 ALL BROWSER E2E TESTS PASSED 100%!")
        print(f"Verified booking {booking_ref} is completely integrated!")
        print("=======================================================\n")

        browser.close()

if __name__ == "__main__":
    run_browser_test()
